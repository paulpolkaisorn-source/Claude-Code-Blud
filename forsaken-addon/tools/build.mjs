// Bundles src/main.ts into packs/Forsaken_BP/scripts/main.js with esbuild.
import * as esbuild from "esbuild";
import path from "node:path";
import { ROOT, BP } from "./lib/fsutil.mjs";

const outfile = path.join(BP, "scripts", "main.js");
const result = await esbuild.build({
  entryPoints: [path.join(ROOT, "src", "main.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2020",
  outfile,
  external: ["@minecraft/server", "@minecraft/server-ui"],
  minify: false,
  sourcemap: false,
  legalComments: "none",
  logLevel: "warning",
  metafile: true,
  banner: {
    js: "// FORSAKEN: Bedrock Edition - unofficial fan project. Not affiliated with or endorsed by the FORSAKEN developers or Roblox.\n// Generated by tools/build.mjs from src/. Do not edit by hand.",
  },
});
const bytes = Object.values(result.metafile.outputs).reduce((n, o) => n + o.bytes, 0);
console.log(`[build] wrote ${path.relative(ROOT, outfile)} (${(bytes / 1024).toFixed(1)} KiB)`);
