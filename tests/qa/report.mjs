// Writes QA.md (repo root) from the recorded check rows, perf data, touch measurements and captured browser errors.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { ROOT } from '../browser-env.mjs';
import { sessions, runEnv } from './harness.mjs';
import { classifyDefects } from './defects.mjs';

const cell = (v) => String(v ?? '').replace(/\|/g, '/').replace(/\n/g, ' ');
const SUITE_OF = { D: 'Desktop (1280x720)', M: 'Mobile (390x844, touch)', P: 'Perf (1280x720, SwiftShader)' };

function median(values) {
  if (!values.length) return null;
  const s = [...values].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
}

export function writeReport(rec, report, meta) {
  const rows = rec.rows;
  const pass = rows.filter((r) => r.status === 'PASS').length;
  const fail = rows.filter((r) => r.status === 'FAIL').length;
  const failed = rows.filter((r) => r.status === 'FAIL');
  const { open, fixed } = classifyDefects(rows);
  const lines = [];

  lines.push('# QA report: Brawl Arena 3D');
  lines.push('');
  lines.push(`Generated by \`npm run qa\` (tests/qa/run-qa.mjs) on ${new Date().toISOString()}.`);
  lines.push('');
  lines.push(`**Overall: ${fail ? 'FAIL' : 'PASS'}.** ${pass} passed, ${fail} failed, ${rows.length} checks, ${(meta.totalMs / 1000).toFixed(0)} s.`);
  lines.push('');
  lines.push('## Summary by suite');
  lines.push('');
  lines.push('| Suite | Passed | Failed |');
  lines.push('|---|---|---|');
  for (const [key, label] of Object.entries(SUITE_OF)) {
    const mine = rows.filter((r) => r.id.startsWith(key));
    if (!mine.length) continue;
    lines.push(`| ${label} | ${mine.filter((r) => r.status === 'PASS').length} | ${mine.filter((r) => r.status === 'FAIL').length} |`);
  }
  lines.push('');
  lines.push('## Environment and how to run');
  lines.push('');
  lines.push(`- Chromium ${runEnv.chromium || 'unknown'} (headless, Playwright ${meta.playwrightVersion}), Node ${process.version}, ${os.cpus().length} vCPU.`);
  lines.push('- WebGL runs on ANGLE + SwiftShader (CPU rasterizer). Absolute FPS is environment-bound and is not representative of a GPU; compare quality levels only.');
  lines.push('- Desktop: 1280x720, DPR 1, mouse and keyboard. Mobile: 390x844, DPR 2, touch, `index.html?mobile`.');
  lines.push('- Touch: pads, menus and HUD are driven with Playwright\'s touch tap; the left-stick drag uses raw CDP touch events. The game\'s tap window (TAP_MS) is 350 ms.');
  lines.push('- Timing: the sim advances by at most about 0.1 s per rendered frame (observed), so under SwiftShader the match clock runs slower than wall time. Tests wait on game state with timeouts, not on frame counts; bulk sim time uses `fastForward`.');
  lines.push(`- Suites run: ${meta.suites.join(', ')}${meta.filtered ? ' (filtered run; this file is not rewritten by filtered runs)' : ''}.`);
  lines.push('- Run: `npm run qa` (exit 1 on any failure). Development filter: `node tests/qa/run-qa.mjs --suite=desktop --only=D09`.');
  lines.push('');
  lines.push('## Checks');
  lines.push('');
  lines.push('| ID | Area | Check | Result | Time | Detail |');
  lines.push('|---|---|---|---|---|---|');
  for (const r of rows) {
    lines.push(`| ${cell(r.id)} | ${cell(r.area)} | ${cell(r.name)} | ${r.status} | ${(r.ms / 1000).toFixed(1)} s | ${cell(r.detail)} |`);
  }
  lines.push('');
  lines.push('## Performance');
  lines.push('');
  if (report.reference) {
    lines.push(`Reference (${report.reference.scene}): ${report.reference.fps.toFixed(1)} fps over ${report.reference.frames} frames on this same SwiftShader setup. It is a context figure only: the game's live play runs at a fraction of this rate in the same environment.`);
    lines.push('');
  }
  if (report.perf && report.perf.length) {
    lines.push('| Scenario | Quality | Frames | Avg FPS | Worst-frame FPS | Draw calls avg | Draw calls max | Game-reported FPS avg | Clock advanced |');
    lines.push('|---|---|---|---|---|---|---|---|---|');
    for (const p of report.perf) {
      lines.push(`| ${cell(p.scenario)} | ${cell(p.quality)} | ${p.frames} | ${p.avgFps.toFixed(2)} | ${p.minFps.toFixed(2)} | ${p.avgDraws.toFixed(0)} | ${p.maxDraws} | ${p.gameFpsAvg.toFixed(1)} | ${p.clockAdvance.toFixed(1)} s |`);
    }
    lines.push('');
    lines.push('Avg FPS = rendered frames / wall seconds from requestAnimationFrame timestamps. Worst-frame FPS = 1 / longest frame interval. Game-reported FPS is `window.__BRAWL__.stats().fps`, shown for comparison. Draw calls are `stats().drawCalls` sampled every frame; the budget is 150 per frame (ARCHITECTURE.md). Live play = 6 brawlers with bots, the player holding D and clicking every 1.5 s; 4 s warm-up before each 10 s window.');
    lines.push('');
  } else {
    lines.push('No perf samples were recorded in this run.');
    lines.push('');
  }
  lines.push('## Touch input measurement');
  lines.push('');
  if (report.touchTaps && report.touchTaps.length) {
    lines.push('Informational, not a pass/fail check. Presses are under 300 ms. Each press is taken only when the player has ammo; before it the sim is advanced with `fastForward` (full ammo, attack gap clear) and at least 0.45 s of wall time passes since the previous press. A press counts as fired when a player shot event follows within 4 s.');
    lines.push('');
    lines.push('| Press | Fired / trials | Skipped (no ammo) | Median press-to-shot |');
    lines.push('|---|---|---|---|');
    for (const r of report.touchTaps) {
      const label = r.method === 'raw CDP' ? `raw CDP touchStart, ${r.ms} ms hold, touchEnd` : 'Playwright locator tap';
      const med = median(r.delays);
      lines.push(`| ${cell(label)} | ${r.fired} / ${r.trials} | ${r.noAmmo} | ${med === null ? '-' : `${Math.round(med)} ms`} |`);
    }
    lines.push('');
  } else {
    lines.push(`No touch measurement was recorded${report.touchTapsError ? `: ${cell(report.touchTapsError)}` : '.'}`);
    lines.push('');
  }
  lines.push('## Errors and warnings captured');
  lines.push('');
  const groups = new Map();
  for (const s of sessions) {
    for (const e of s.errors) {
      const text = String(e).split('\n')[0].slice(0, 200);
      const key = `${s.name} | ${text}`;
      const g = groups.get(key) || { session: s.name, text, count: 0 };
      g.count += 1;
      groups.set(key, g);
    }
  }
  if (!groups.size) {
    lines.push('None. No console errors, page errors, failed requests or HTTP 400+ responses were captured in any session.');
  } else {
    lines.push('| Session | Count | First line |');
    lines.push('|---|---|---|');
    for (const g of groups.values()) lines.push(`| ${cell(g.session)} | ${g.count} | ${cell(g.text)} |`);
  }
  lines.push('');
  lines.push('## Game defects (open)');
  lines.push('');
  if (!open.length && !failed.length) {
    lines.push('None. No open defects and no failed checks in this run.');
    lines.push('');
  } else {
    if (open.length) {
      for (const d of open) {
        lines.push(`### ${d.id} (${d.severity}${d.regressed ? ', REGRESSED' : ''}): ${d.title}`);
        lines.push('');
        lines.push(`- Failing checks: ${d.checks.length ? d.checks.join(', ') : 'none this run (not reproduced)'}`);
        lines.push(`- Evidence: ${d.evidence}`);
        lines.push(`- Impact: ${d.impact}`);
        lines.push(`- Suggested fix: ${d.fix}`);
        lines.push('');
      }
    } else {
      lines.push('No open defects. Failed checks not matched to a defect are listed below.');
      lines.push('');
    }
    const explained = new Set(open.flatMap((d) => d.checks));
    const unexplained = failed.filter((r) => !explained.has(r.id));
    if (unexplained.length) {
      lines.push('### Other failed checks (not yet diagnosed)');
      lines.push('');
      for (const r of unexplained) lines.push(`- **${r.id}** ${r.name}: ${r.detail}`);
      lines.push('');
    }
  }
  lines.push('## Fixed defects');
  lines.push('');
  if (!fixed.length) {
    lines.push('None recorded.');
    lines.push('');
  }
  for (const d of fixed) {
    const notReproduced = d.verified.every((v) => v.status === 'PASS');
    lines.push(`### ${d.id} (${d.severity}, fixed): ${d.title}`);
    lines.push('');
    lines.push(`- Status this run: ${notReproduced ? 'not reproduced' : 'not fully verified'}. Verifying checks: ${d.verified.map((v) => `${v.id} ${v.status}`).join(', ')}.`);
    lines.push(`- What it was: ${d.impact}`);
    lines.push(`- Fix: ${d.fixNote}`);
    lines.push('');
  }
  lines.push('## Known limits of this suite');
  lines.push('');
  lines.push('- Perf numbers are SwiftShader numbers from a 4-vCPU container. Use them for quality-to-quality comparison only.');
  lines.push('- Supers, dash, totems, walls, bush visibility and bot movement are verified through game state and bus events (`window.__BRAWL__`), not pixels. Audio and visual polish are not checked.');
  const taps = report.touchTaps || [];
  const raw = taps.filter((r) => r.method === 'raw CDP');
  const pw = taps.filter((r) => r.method !== 'raw CDP');
  const total = (rs, k) => rs.reduce((a, r) => a + r[k], 0);
  lines.push(taps.length
    ? `- Raw CDP touch presses: this run's measurement (Touch input measurement above) found raw CDP presses under 300 ms firing on ${total(raw, 'fired')} of ${total(raw, 'trials')} trials, and Playwright taps on ${total(pw, 'fired')} of ${total(pw, 'trials')}. Presses of 300 ms or longer were not measured, and the suite drives the pads with Playwright taps. Any gap for raw CDP presses (game touch handler or CDP injection) is not confirmed; verify on a real touch device before filing it as a game defect.`
    : '- Raw CDP touch presses: no measurement in this run.');
  lines.push('- The left-stick drag uses raw CDP touchStart/touchMove/touchEnd and passed in every run (M04).');
  lines.push('- Results and flows were checked on the 1280x720 and 390x844 viewports only.');
  lines.push('');
  const file = path.join(ROOT, 'QA.md');
  fs.writeFileSync(file, lines.join('\n'));
  return file;
}
